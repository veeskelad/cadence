// Сборка панели Data Driver (ScriptUI для EffectCraft) из src/ в один файл.
//   node build.mjs [--out <папка>]
// По умолчанию результат идёт в $CADENCE_WORK/data-motion-graphics/out (или ./work/... от текущей папки).
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
const root = new URL('./', import.meta.url);
const argOut = process.argv.indexOf('--out');
const out = resolve(argOut > 0 ? process.argv[argOut + 1]
  : (process.env.CADENCE_WORK || resolve(process.cwd(), 'work')) + '/data-motion-graphics/out');
const source = '// Data Driver 1.1.1 — EffectCraft ScriptUI panel\n// Generated by build.mjs. Edit src/.\n' +
  (await Promise.all(['core.js', 'host.js', 'panel.js'].map(f => readFile(new URL('src/' + f, root), 'utf8')))).join('\n');
await mkdir(out, { recursive: true });
await writeFile(out + '/Data Driver.jsx', source);
await writeFile(out + '/Data Driver.jsx.sha256', createHash('sha256').update(source).digest('hex') + '\n');
console.log('Собрано: ' + out + '/Data Driver.jsx');
