// Значки для досок-инфографики: плоские залитые силуэты, как вырезанная бумага или наклейка.
//
// Правила рисовки (от владельца, не нарушать):
//   - каждый элемент — залитая фигура (fill=), никаких stroke, линий-палочек и волосков;
//     стрелка часов, ручка, антенна — скруглённый прямоугольник или контур (bar(), arcBand());
//   - каждая часть касается тела; отдельно висят только намеренные капли (пар, искры);
//   - 2–4 цвета на значок: c.a — основная заливка (есть в каждом), c.b — вторая, c.c — мелкий акцент,
//     c.dark — окна, дырки, зрачки (только внутри силуэта: на тёмной доске внешние тёмные части пропадают),
//     c.paper — светлый блик; c.ink — обводка-подложка (тёмный силуэт чуть больше фигуры позади неё, как у users);
//   - значок по центру, занимает примерно 8..92 в поле 100×100; без <text>: шрифты в рендере не гарантированы;
//   - только нейтральные предметы: без знаков реальных брендов, без оружия.
//
// Контракт:
//   ICONS[name](c) — внутренняя разметка <svg viewBox="0 0 100 100"> (только фигуры), c = {a, b, c, ink, paper, dark};
//   icon(name, colors) — целый <svg>, имя можно дать по-русски (ALIASES); незнакомое имя — исключение;
//   ALIASES — русское слово → английское имя; iconNames() — список имён.
// Цвета приходят строками CSS (обычно var(--…)) и попадают в атрибут fill как есть.

// ---------- помощники ----------

const n = (x) => +x.toFixed(2);
const rad = (deg) => (deg * Math.PI) / 180;
const pt = (cx, cy, r, deg) => [n(cx + r * Math.cos(rad(deg))), n(cy + r * Math.sin(rad(deg)))];
const tf = (t) => (t ? ` transform="${t}"` : '');

// скруглённый прямоугольник
const R = (x, y, w, h, r, f, t) => `<rect x="${n(x)}" y="${n(y)}" width="${n(w)}" height="${n(h)}" rx="${n(r)}" fill="${f}"${tf(t)}/>`;
const C = (cx, cy, r, f) => `<circle cx="${n(cx)}" cy="${n(cy)}" r="${n(r)}" fill="${f}"/>`;
const E = (cx, cy, rx, ry, f, t) => `<ellipse cx="${n(cx)}" cy="${n(cy)}" rx="${n(rx)}" ry="${n(ry)}" fill="${f}"${tf(t)}/>`;
const P = (d, f, t) => `<path d="${d}" fill="${f}"${tf(t)}/>`;
const G = (t, inner) => `<g transform="${t}">${inner}</g>`;

// толстая «линия» от точки к точке: прямоугольник с круглыми концами
function bar(x1, y1, x2, y2, w, f) {
  const len = Math.hypot(x2 - x1, y2 - y1);
  const ang = (Math.atan2(y2 - y1, x2 - x1) * 180) / Math.PI;
  return R(x1 - w / 2, y1 - w / 2, len + w, w, w / 2, f, `rotate(${n(ang)} ${n(x1)} ${n(y1)})`);
}

// кольцо с настоящей дыркой (evenodd), без clipPath и id
function ring(cx, cy, ro, ri, f) {
  const circ = (r) => `M${n(cx - r)} ${n(cy)}A${n(r)} ${n(r)} 0 1 0 ${n(cx + r)} ${n(cy)}A${n(r)} ${n(r)} 0 1 0 ${n(cx - r)} ${n(cy)}Z`;
  return `<path d="${circ(ro)}${circ(ri)}" fill="${f}" fill-rule="evenodd"/>`;
}

// дуга-полоса: средняя линия радиуса r, ширина w, углы в градусах (0 — вправо, по часовой), круглые концы
function arcBand(cx, cy, r, w, a0, a1, f, caps = true) {
  const ro = r + w / 2, ri = r - w / 2, large = a1 - a0 > 180 ? 1 : 0;
  const [ox0, oy0] = pt(cx, cy, ro, a0), [ox1, oy1] = pt(cx, cy, ro, a1);
  const [ix1, iy1] = pt(cx, cy, ri, a1), [ix0, iy0] = pt(cx, cy, ri, a0);
  let s = P(`M${ox0} ${oy0}A${n(ro)} ${n(ro)} 0 ${large} 1 ${ox1} ${oy1}L${ix1} ${iy1}A${n(ri)} ${n(ri)} 0 ${large} 0 ${ix0} ${iy0}Z`, f);
  if (caps) {
    const [x0, y0] = pt(cx, cy, r, a0), [x1, y1] = pt(cx, cy, r, a1);
    s += C(x0, y0, w / 2, f) + C(x1, y1, w / 2, f);
  }
  return s;
}

// звезда: k лучей, внешний и внутренний радиус
function starD(cx, cy, ro, ri, k, rot = -90) {
  const pts = [];
  for (let i = 0; i < k * 2; i++) pts.push(pt(cx, cy, i % 2 ? ri : ro, rot + (i * 180) / k));
  return `M${pts.map((p) => p.join(' ')).join('L')}Z`;
}

// многоугольник со скруглёнными углами
function roundPoly(points, r) {
  const m = points.length;
  let d = '';
  for (let i = 0; i < m; i++) {
    const p = points[i], prev = points[(i + m - 1) % m], next = points[(i + 1) % m];
    const toward = (q) => {
      const dx = q[0] - p[0], dy = q[1] - p[1], len = Math.hypot(dx, dy), k = Math.min(r, len / 2) / len;
      return [n(p[0] + dx * k), n(p[1] + dy * k)];
    };
    const A = toward(prev), B = toward(next);
    d += `${i ? 'L' : 'M'}${A[0]} ${A[1]}Q${p[0]} ${p[1]} ${B[0]} ${B[1]}`;
  }
  return `${d}Z`;
}

// шестерня: зубья трапецией, впадины дугой
function gearD(cx, cy, ro, rr, k) {
  const step = 360 / k, half = step * 0.2, base = step * 0.3;
  let d = '';
  for (let i = 0; i < k; i++) {
    const t = -90 + i * step;
    const p1 = pt(cx, cy, rr, t - base), p2 = pt(cx, cy, ro, t - half), p3 = pt(cx, cy, ro, t + half), p4 = pt(cx, cy, rr, t + base);
    const nx = pt(cx, cy, rr, t + step - base);
    d += `${i ? 'L' : 'M'}${p1.join(' ')}L${p2.join(' ')}L${p3.join(' ')}L${p4.join(' ')}A${rr} ${rr} 0 0 1 ${nx.join(' ')}`;
  }
  return `${d}Z`;
}

